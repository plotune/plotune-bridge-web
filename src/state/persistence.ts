// Browser-owned convenience state only. Never serialize WorkspaceState or a device descriptor.
import { DEFAULT_DIAG, type DiagSettings } from '../diagnostics/settings';
import { parseTarget } from '../lib/target';

export const WORKSPACE_KEY = 'bw.workspace';
export type PageId = 'capture' | 'diagnostics' | 'device';
export const PANEL_IDS = {
  capture: ['trace', 'channels', 'stats', 'transmit'],
  diagnostics: ['link', 'uds', 'xcp'],
  device: ['device'],
} as const;

export interface DevicePreferences {
  target: string;
  captureChannels: number[];
  transmitChannel: number;
}
export interface SavedDevice extends DevicePreferences { id: string; label: string }
export interface SavedWorkspace {
  version: 1;
  devices: SavedDevice[];
  activeId: string;
  traceView: string;
  page: PageId;
  hidden: Record<PageId, string[]>;
  diagnostics: DiagSettings;
  permissionExplained: boolean;
}
export type StoragePort = Pick<Storage, 'getItem' | 'setItem' | 'removeItem'>;

export function emptyWorkspace(): SavedWorkspace {
  return { version: 1, devices: [], activeId: '', traceView: 'all', page: 'capture', hidden: { capture: [], diagnostics: [], device: [] }, diagnostics: { ...DEFAULT_DIAG }, permissionExplained: false };
}
const record = (v: unknown): v is Record<string, unknown> => v !== null && typeof v === 'object' && !Array.isArray(v);
const pages = Object.keys(PANEL_IDS) as PageId[];
export const isPage = (v: unknown): v is PageId => pages.includes(v as PageId);

/** Only ordinary root device addresses and well-formed remote targets are remembered. Custom paths, queries and fragments may contain secrets. */
export function rememberableTarget(input: unknown): string | null {
  if (typeof input !== 'string' || input.length > 2048) return null;
  const target = parseTarget(input);
  if (!target.ok) return null;
  // A remote target holds only the project and device IDs, never a ticket or token.
  if (target.remote) return target.url;
  const url = new URL(target.url);
  return !url.username && !url.password && !url.search && !url.hash && url.pathname === '/' ? target.url : null;
}

function channels(v: unknown): number[] {
  return Array.isArray(v) ? [...new Set(v.filter((c) => c === 1 || c === 2))] : [1, 2];
}
function diagnostics(v: unknown): DiagSettings {
  const result = { ...DEFAULT_DIAG };
  if (!record(v)) return result;
  for (const k of ['udsRequestId', 'udsResponseId', 'xcpRequestId', 'xcpResponseId'] as const) {
    if (typeof v[k] === 'string' && v[k].length <= 16) result[k] = v[k];
  }
  for (const k of ['extended', 'xcpPadTo8'] as const) if (typeof v[k] === 'boolean') result[k] = v[k];
  if (v.channel === 1 || v.channel === 2) result.channel = v.channel;
  if (v.padding === '00' || v.padding === 'AA' || v.padding === 'none') result.padding = v.padding;
  if (typeof v.timeoutMs === 'number' && Number.isInteger(v.timeoutMs) && v.timeoutMs >= 50 && v.timeoutMs <= 10_000) result.timeoutMs = v.timeoutMs;
  return result;
}

function decode(v: unknown): SavedWorkspace {
  if (!record(v) || v.version !== 1 || !Array.isArray(v.devices) || v.devices.length > 8) return emptyWorkspace();
  const result = emptyWorkspace();
  const ids = new Set<string>();
  for (const d of v.devices) {
    if (!record(d) || typeof d.id !== 'string' || !/^d[1-9]\d{0,5}$/.test(d.id) || ids.has(d.id)) return emptyWorkspace();
    const target = rememberableTarget(d.target);
    if (!target) return emptyWorkspace();
    ids.add(d.id);
    // Labels are generated by the app; arbitrary stored strings are not copied.
    result.devices.push({ id: d.id, label: `Bridge ${Number(d.id.slice(1))}`, target, captureChannels: channels(d.captureChannels), transmitChannel: d.transmitChannel === 2 ? 2 : 1 });
  }
  result.activeId = typeof v.activeId === 'string' && ids.has(v.activeId) ? v.activeId : (result.devices[0]?.id ?? '');
  result.traceView = typeof v.traceView === 'string' && ids.has(v.traceView) ? v.traceView : 'all';
  result.page = isPage(v.page) ? v.page : 'capture';
  result.permissionExplained = v.permissionExplained === true;
  if (record(v.hidden)) {
    for (const page of pages) {
      const value = v.hidden[page];
      if (Array.isArray(value)) result.hidden[page] = PANEL_IDS[page].filter((id) => value.includes(id));
    }
  }
  result.diagnostics = diagnostics(v.diagnostics);
  return result;
}

/** One explicit migration: previous unversioned bw.* keys → v1. Unsupported versions/corruption reset the shell. */
export class WorkspacePersistence {
  private snapshot: SavedWorkspace;
  private lastWritten = '';
  constructor(private readonly storage: () => StoragePort | null = () => localStorage) {
    let snapshot = emptyWorkspace();
    try {
      const s = storage();
      const raw = s?.getItem(WORKSPACE_KEY);
      if (raw != null) snapshot = decode(JSON.parse(raw));
      else if (s) {
        const target = rememberableTarget(s.getItem('bw.target'));
        snapshot = decode({ ...snapshot,
          devices: target ? [{ id: 'd1', target }] : [],
          permissionExplained: s.getItem('bw.permissionExplained') === '1',
          diagnostics: this.legacyJson(s, 'bw.diagnostics'),
          hidden: Object.fromEntries(pages.map((p) => [p, this.legacyJson(s, `bw.hidden.${p}`)])),
        });
      }
    } catch { /* unavailable or corrupt storage: a clean, fully usable shell */ }
    this.snapshot = snapshot;
    this.save(snapshot);
    // Retire the old address writer too: it allowed secret-bearing queries/paths.
    try {
      const s = storage();
      for (const key of ['bw.target', 'bw.permissionExplained', 'bw.diagnostics', ...pages.map((p) => `bw.hidden.${p}`)]) s?.removeItem(key);
    } catch { /* storage may be denied */ }
  }
  private legacyJson(s: StoragePort, key: string): unknown {
    try { return JSON.parse(s.getItem(key) ?? 'null'); } catch { return null; }
  }
  load(): SavedWorkspace { return this.snapshot; }
  save(value: SavedWorkspace): void {
    const safe = decode(value); // enforce allowlists on writes as well as reads
    this.snapshot = safe;
    const serialized = JSON.stringify(safe);
    if (serialized === this.lastWritten) return;
    this.lastWritten = serialized; // do not retry on every incoming frame when writes fail
    try { this.storage()?.setItem(WORKSPACE_KEY, serialized); } catch { /* quota/private mode: memory only */ }
  }
}
